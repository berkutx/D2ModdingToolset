template <std::size_t Size>
inline bool expectBytes(std::uintptr_t address,
                        const std::array<std::uint8_t, Size>& expected,
                        const char* label,
                        std::string& error)
{
    if (std::memcmp(reinterpret_cast<const void*>(address), expected.data(), Size) == 0)
        return true;

    error = "simultaneous-turn Russobit preflight failed at ";
    error += label ? label : "unknown site";
    return false;
}

inline std::uintptr_t decodeRelativeCallTarget(std::uintptr_t callAddress)
{
    std::int32_t displacement = 0;
    std::memcpy(&displacement, reinterpret_cast<const void*>(callAddress + 1),
                sizeof(displacement));
    return callAddress + 5 + displacement;
}

